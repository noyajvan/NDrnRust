fn main() {
    // Ініціалізація периферії
    let peripherals = Peripherals::take().unwrap();
    let sysloop = EspSystemEventLoop::take().unwrap();
    let nvs = EspDefaultNvsPartition::take().unwrap();

    // Налаштування UART для зв'язку з польотним контролером
    let uart_config = UartConfig::default().baudrate(Hertz(115_200));
    let uart = UartDriver::new(
        peripherals.uart0,
        peripherals.pins.gpio44,
        peripherals.pins.gpio43,
        Option::<Gpio0>::None,
        Option::<Gpio0>::None,
        &uart_config,
    )
    .unwrap();

    // Налаштування NeoPixel (WS2812) на GPIO48
    let neopixel = ws2812_esp32_rmt_driver::Ws2812Rmt::new(
        peripherals.rmt.channel0,
        peripherals.pins.gpio48,
    )
    .unwrap();

    // Налаштування WiFi
    let mut wifi = WifiDriver::new(peripherals.modem, sysloop, nvs).unwrap();
    let mut wifi_handle = WifiHandle::new(&mut wifi);

    // Головний цикл
    loop {
        // Тут буде вся логіка, аналогічна Arduino-коду
        FreeRtos::delay_ms(2);
    }
}
